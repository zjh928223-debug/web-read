const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const repoRoot = path.resolve(__dirname, '..')
const legacyPath = path.join(repoRoot, 'src', 'stores', 'marks.js')
const piniaSource = fs.readFileSync(path.join(repoRoot, 'src', 'pinia-stores', 'marks.js'), 'utf8')
const featureDepsSource = fs.readFileSync(path.join(repoRoot, 'src', 'composables', 'reader-feature-runtime-deps.js'), 'utf8')
const keyboardRuntimeSource = fs.readFileSync(path.join(repoRoot, 'src', 'composables', 'reader-keyboard-runtime.js'), 'utf8')
const persistenceSource = fs.readFileSync(path.join(repoRoot, 'src', 'composables', 'use-reader-session-persistence.js'), 'utf8')

assert.equal(fs.existsSync(legacyPath), false, 'legacy marks compatibility store must be deleted')
assert.ok(piniaSource.includes('function syncVisual(globalIndex, isMarked)'))
assert.ok(piniaSource.includes('async function toggle(markedMap, currentWordIndex, words, saveToDB, syncAnnotationFn)'))
assert.ok(featureDepsSource.includes('marksStore.toggle.bind(marksStore)'))
assert.ok(keyboardRuntimeSource.includes('deps.marksStore.toggleMark('))
assert.ok(persistenceSource.includes('marksStore.syncVisual(mark.globalIndex, true)'))
assert.equal(featureDepsSource.includes('__marksStore'), false)
assert.equal(persistenceSource.includes('__marksStore'), false)

console.log('marks store owner check passed')
